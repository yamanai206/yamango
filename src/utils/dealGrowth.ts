export interface MonthlyGrowthPoint {
  monthKey: string; // e.g. "2026-05"
  monthName: string; // e.g. "أيار 2026"
  shortMonth: string; // e.g. "أيار"
  monthIndex: number; // 0-5
  totalDeals: number;
  completedDeals: number;
  cancelledDeals: number;
  inProgressDeals: number;
  completionRate: number; // 0 to 100%
  totalVolumeUSD: number;
  totalVolumeSYP: number;
}

export interface SixMonthGrowthSummary {
  dataPoints: MonthlyGrowthPoint[];
  totalDealsSixMonths: number;
  completedDealsSixMonths: number;
  cancelledDealsSixMonths: number;
  overallCompletionRate: number;
  growthPercentage: number; // percentage change in monthly total from month 0 to month 5
  completedGrowthPercentage: number;
  topZone: {
    id: ZoneLocation;
    name: string;
    total: number;
    completed: number;
  };
  averageMonthlyDeals: number;
  averageMonthlyCompleted: number;
  selectedZoneLabel: string;
}

