/**
 * Computes 6-month growth data for deals and completed operations,
 * optionally filtered by sub-district / zone.
 */
export function computeSixMonthDealGrowth(
  deals: Deal[] = [],
  zoneFilter: ZoneLocation | 'all' = 'all',
  referenceDate: Date = new Date('2026-10-25')
): SixMonthGrowthSummary {
  // Merge live deals with historical baseline to ensure full 6-month trajectory
  const dealMap = new Map<string, Deal>();

  // Add historical baseline first
  for (const h of HISTORICAL_BASELINE_DEALS) {
    dealMap.set(h.id, h);
  }

  // Add or override with live deals
  for (const d of deals) {
    // If deal doesn't have an explicit zone, set default based on listing or al_kafr
    const dealWithZone: Deal = {
      ...d,
      zone: d.zone || (d.id === 'deal_102' || d.id === 'deal_103' ? 'suwayda' : d.id === 'deal_107' || d.id === 'deal_110' ? 'shahba' : d.id === 'deal_109' ? 'salkhad' : 'al_kafr'),
    };
    dealMap.set(d.id, dealWithZone);
  }

  const allCombinedDeals = Array.from(dealMap.values());

  // Filter by zone if selected
  const zoneFilteredDeals = zoneFilter === 'all'
    ? allCombinedDeals
    : allCombinedDeals.filter((d) => d.zone === zoneFilter);

  // Generate the 6 month intervals ending at referenceDate
  const targetYear = referenceDate.getFullYear();
  const targetMonth = referenceDate.getMonth(); // 0-indexed (9 for Oct 2026)

  const monthConfigs: { year: number; month: number; key: string; name: string; short: string }[] = [];

  for (let i = 5; i >= 0; i--) {
    const d = new Date(targetYear, targetMonth - i, 1);
    const y = d.getFullYear();
    const m = d.getMonth();
    const key = `${y}-${String(m + 1).padStart(2, '0')}`;
    const monthName = `${ARABIC_MONTH_NAMES_LIST[m]} ${y}`;
    const short = ARABIC_MONTH_NAMES_LIST[m];
    monthConfigs.push({ year: y, month: m, key, name: monthName, short });
  }

  // Aggregate deals per month
  const dataPoints: MonthlyGrowthPoint[] = monthConfigs.map((cfg, idx) => {
    const dealsInMonth = zoneFilteredDeals.filter((deal) => {
      const timestamp = deal.completedAt
        ? new Date(deal.completedAt.replace(' ', 'T')).getTime()
        : deal.cancelledAt
        ? new Date(deal.cancelledAt.replace(' ', 'T')).getTime()
        : deal.createdAt;
      const d = new Date(timestamp);
      return d.getFullYear() === cfg.year && d.getMonth() === cfg.month;
    });

    let completed = 0;
    let cancelled = 0;
    let inProgress = 0;
    let volUSD = 0;
    let volSYP = 0;

    for (const deal of dealsInMonth) {
      if (deal.status === 'completed') {
        completed++;
      } else if (deal.status === 'cancelled') {
        cancelled++;
      } else {
        inProgress++;
      }

      if (deal.currency === 'USD') {
        volUSD += deal.agreedPrice;
      } else {
        volSYP += deal.agreedPrice;
      }
    }

    const total = dealsInMonth.length;
    const rate = total > 0 ? Math.round((completed / total) * 100) : 0;

    return {
      monthKey: cfg.key,
      monthName: cfg.name,
      shortMonth: cfg.short,
      monthIndex: idx,
      totalDeals: total,
      completedDeals: completed,
      cancelledDeals: cancelled,
      inProgressDeals: inProgress,
      completionRate: rate,
      totalVolumeUSD: volUSD,
      totalVolumeSYP: volSYP,
    };
  });

  // Calculate overall metrics
  const totalDealsSixMonths = dataPoints.reduce((acc, p) => acc + p.totalDeals, 0);
  const completedDealsSixMonths = dataPoints.reduce((acc, p) => acc + p.completedDeals, 0);
  const cancelledDealsSixMonths = dataPoints.reduce((acc, p) => acc + p.cancelledDeals, 0);
  const overallCompletionRate = totalDealsSixMonths > 0
    ? Math.round((completedDealsSixMonths / totalDealsSixMonths) * 100)
    : 0;

  // Growth percentages from Month 0 (first in window) to Month 5 (latest in window)
  const firstMonthTotal = dataPoints[0]?.totalDeals || 1;
  const lastMonthTotal = dataPoints[dataPoints.length - 1]?.totalDeals || 0;
  const growthPercentage = Math.round(((lastMonthTotal - firstMonthTotal) / firstMonthTotal) * 100);

  const firstMonthCompleted = dataPoints[0]?.completedDeals || 1;
  const lastMonthCompleted = dataPoints[dataPoints.length - 1]?.completedDeals || 0;
  const completedGrowthPercentage = Math.round(((lastMonthCompleted - firstMonthCompleted) / firstMonthCompleted) * 100);

  // Determine top performing zone across the 6-month period
  const zoneCounts: Record<ZoneLocation, { total: number; completed: number }> = {
    al_kafr: { total: 0, completed: 0 },
    suwayda: { total: 0, completed: 0 },
    salkhad: { total: 0, completed: 0 },
    shahba: { total: 0, completed: 0 },
    al_qurayya: { total: 0, completed: 0 },
    mazraa: { total: 0, completed: 0 },
    ariqa: { total: 0, completed: 0 },
  };

  for (const deal of allCombinedDeals) {
    const timestamp = deal.completedAt
      ? new Date(deal.completedAt.replace(' ', 'T')).getTime()
      : deal.createdAt;
    const d = new Date(timestamp);
    // Only count if within the 6-month window
    const firstConfig = monthConfigs[0];
    const lastConfig = monthConfigs[monthConfigs.length - 1];
    const dealMonth = d.getFullYear() * 12 + d.getMonth();
    const firstMonthVal = firstConfig.year * 12 + firstConfig.month;
    const lastMonthVal = lastConfig.year * 12 + lastConfig.month;

    if (dealMonth >= firstMonthVal && dealMonth <= lastMonthVal) {
      const z = (deal.zone || 'al_kafr') as ZoneLocation;
      if (zoneCounts[z]) {
        zoneCounts[z].total++;
        if (deal.status === 'completed') {
          zoneCounts[z].completed++;
        }
      }
    }
  }

  let topZoneId: ZoneLocation = 'al_kafr';
  let topZoneCount = -1;
  for (const [zId, counts] of Object.entries(zoneCounts)) {
    if (counts.completed > topZoneCount) {
      topZoneCount = counts.completed;
      topZoneId = zId as ZoneLocation;
    }
  }

  const selectedZoneLabel = zoneFilter === 'all'
    ? 'كافة النواحي والمناطق (السويداء)'
    : ZONE_NAMES_ARABIC[zoneFilter] || zoneFilter;

  return {
    dataPoints,
    totalDealsSixMonths,
    completedDealsSixMonths,
    cancelledDealsSixMonths,
    overallCompletionRate,
    growthPercentage,
    completedGrowthPercentage,
    topZone: {
      id: topZoneId,
      name: ZONE_NAMES_ARABIC[topZoneId] || 'بلدة الكفر',
      total: zoneCounts[topZoneId]?.total || 0,
      completed: zoneCounts[topZoneId]?.completed || 0,
    },
    averageMonthlyDeals: Math.round((totalDealsSixMonths / 6) * 10) / 10,
    averageMonthlyCompleted: Math.round((completedDealsSixMonths / 6) * 10) / 10,
    selectedZoneLabel,
  };
}
